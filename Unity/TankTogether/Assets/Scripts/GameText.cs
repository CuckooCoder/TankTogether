        static readonly int[] TranslationOrder=MakeOrder();
        static int[] MakeOrder(){var order=new int[Pairs.GetLength(0)];for(int i=0;i<order.Length;i++)order[i]=i;System.Array.Sort(order,(a,b)=>Pairs[b,0].Length.CompareTo(Pairs[a,0].Length));return order;}
        public static string Translate(string text)
        {
            if(PlayerPreferences.Data.language==0||string.IsNullOrEmpty(text))return text;
            if(text=="低")return "Low";
            if(text=="中")return "Medium";
            if(text=="高")return "High";

            foreach(int i in TranslationOrder)text=text.Replace(Pairs[i,0],Pairs[i,1]);
            return text;
        }
